import { createContext, ReactNode, useContext, useEffect, useState } from 'react'

/**
 * Sprache der Oberfläche. Der deutsche Text ist zugleich der Schlüssel:
 * t('Heute') liefert auf Deutsch genau diesen Text, auf Englisch die Übersetzung.
 * Platzhalter in geschweiften Klammern werden ersetzt: t('{n} Notizen', { n: 3 }).
 * Die Wahl gilt pro Gerät (wie der Farbmodus).
 */
export type Lang = 'de' | 'en'
export const LANGS: { code: Lang; short: string; label: string }[] = [
  { code: 'de', short: 'DE', label: 'Deutsch' },
  { code: 'en', short: 'EN', label: 'English' },
]

const KEY = '12wm-lang'
function initial(): Lang {
  try { return localStorage.getItem(KEY) === 'en' ? 'en' : 'de' } catch { return 'de' }
}
let current: Lang = initial()

export const getLang = () => current
/** Gebietsschema für Datums- und Zeitangaben */
export const locale = () => (current === 'en' ? 'en-GB' : 'de-DE')

const missing = new Set<string>()
export function t(text: string, vars?: Record<string, string | number>): string {
  let out = text
  if (current === 'en' && text) {
    const hit = EN[text]
    if (hit !== undefined) out = hit
    else if (import.meta.env.DEV && !missing.has(text)) { missing.add(text); console.warn('[i18n] fehlt:', text) }
  }
  if (vars) for (const k in vars) out = out.split(`{${k}}`).join(String(vars[k]))
  return out
}

const Ctx = createContext<{ lang: Lang; setLang: (l: Lang) => void }>({ lang: current, setLang: () => {} })
export const useLang = () => useContext(Ctx)

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setState] = useState<Lang>(current)
  const setLang = (l: Lang) => {
    current = l
    try { localStorage.setItem(KEY, l) } catch { /* ignore */ }
    setState(l)
  }
  useEffect(() => { document.documentElement.lang = lang }, [lang])
  return <Ctx.Provider value={{ lang, setLang }}>{children}</Ctx.Provider>
}

